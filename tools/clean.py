def fix_brackets(t):
    # a '(' '[' or '|' printed where the font's ra-vattu was lost: (దోణ -> ద్రోణ, (శీ -> శ్రీ, కుల[స్తీ -> కులస్త్రీ
    def rep(m):
        cl, vs = m.group(1), m.group(2) or ""
        if cl.endswith("్ర"):
            return cl + vs
        if vs == "ీ" and cl == "శ":
            return "శ్రీ"
        return cl + "్ర" + vs
    t = re.sub(rf"[\(\[\|]({CL})([{V}]?)", rep, t)
    t = re.sub(rf"\(({CL})", r"\1", t)
    return t

def fix_ya(t):
    t = re.sub(rf"([{C}])ు\$", r"\1్యు", t)     # యోగు$ -> యోగ్యు
    t = re.sub(rf"([{C}])\$", r"\1్య", t)        # సైన$ము -> సైన్యము
    return t

def strip_tail(t):
    t = t.strip()
    # drop OCR crumbs after the last sentence end: ' క స', ' ఆ...', ' "', etc.
    m = re.search(r"[.?!”\"'](?=[^.?!”]*$)", t)
    if m and len(t) - m.end() <= 8:
        tail = t[m.end():]
        if not re.search(rf"[{C}]{{2,}}[{V}]?[{C}]", tail):
            t = t[:m.end()]
    t = re.sub(r"(\s+(?:[కసఆఈ](?:\.\.\.|\.)?|క్‌|\.\.\.|[\"'”]))+\s*$", "", t)
    t = re.sub(r"\s+([.?!,;:])", r"\1", t)
    return t.strip()

def fix_dhritarashtra(t):
    """Many OCR shapes of ధృతరాష్ట్ర (+ suffix) -> the right word."""
    def rep(m):
        w = m.group(0)
        suf = re.search(r"(ునికి|ుని|ుడు|ుడిట్లు|ులు|ుల|ు)$", w)
        return "ధృతరాష్ట్ర" + (suf.group(1) if suf else "")
    return re.sub(r"(?<![\u0C00-\u0C7F])ధ[\u0C00-\u0C7F\[\(]{0,6}తర[\u0C00-\u0C7F\[\(]{1,9}(?=[\s,.!?:]|$)",
                  lambda m: rep(m) if re.search(r"[షఘపఫమ]", m.group(0)[3:]) else m.group(0), t)

def clean(text):
    t = " ".join(text.split())
    t = t.replace("'", "")
    t = fix_dhritarashtra(t)
    t = t.replace("‌", "").replace("_", " ")
    t = fix_brackets(t)
    t = fix_ya(t)
    for pat, rep in WORDS:
        t = re.sub(pat, rep, t)
    t = re.sub(r"!{2,}", "!", t)
    t = re.sub(r"\s+", " ", t)
    return strip_tail(t)

